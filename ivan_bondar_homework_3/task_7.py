# Напишите программу, кот. запрашивает у пользователя t в гр. цельсия и выводит сообщение о том, холодно ли на улице или тепло
num = int(input('Введите температуру на улице(в гр. по Цельсию): '))
if num >= 0:
    print('На улице тепло, можно ходить голышом!')
else:
    print('На улице холодно, надевай подштанники!')