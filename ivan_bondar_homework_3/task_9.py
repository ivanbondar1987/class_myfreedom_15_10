# Напишите программу, которая запрашивает от пользователя целое число и проверяет, является ли оно положительным или отрицательным, а возможно это 0
str1 = int(input('Введите целое число: '))
if str1 > 0:
    print('Это число положительное')
elif str1 == 0:
    print('0 это 0, умник!')
else:
    print('Это число отрицательное')