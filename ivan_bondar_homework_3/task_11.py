# Необходимо обеспечить ввод имени, причем, чтобы оно было больше 3, но меньше 50 символов
str11 = input('Введите Ваше имя: ')
if len(str11) < 3:
    print('Имя должно содержать не менее 3 символов')
elif len(str11) > 50:
    print('Имя должно содержать не более 50 символов')
else:
    print('Приятно познакомиться!')