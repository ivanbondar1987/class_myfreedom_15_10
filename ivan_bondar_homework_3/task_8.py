# Напишите программу, которая принимает от пользователя 2 целых числа и определяет, является ли первое число кратное второму
string1 = int(input('Введите первое число: '))
string2 = int(input('Введите второе число: '))
if string1 % string2 == 0:
    print('Первое число кратно второму')
else:
    print('Первое число не кратно второму')